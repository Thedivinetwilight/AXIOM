"""Deterministic replay market-data provider.

Replays RECORDED bars (in memory or from a CSV fixture) so Kronos can be
developed, tested and evaluated offline. It never synthesises, resamples,
reorders or repairs data: what was recorded is what is returned, and ordering
or duplication problems are left for the validator to report.

The repository ships deterministic sample fixtures (``data/sample.csv``,
``data/sample_1h.csv`` — generated by ``scripts/make_sample_data.py`` and
labelled there as synthetic). They are fixtures for offline work, never a
substitute for a real provider in production.
"""

from __future__ import annotations

import csv
from collections.abc import Iterable
from datetime import datetime
from pathlib import Path

from axiom.market.provider import (
    MarketDataBar,
    MarketDataError,
    MarketDataProvider,
    MarketDataResult,
)
from axiom.models import utcnow

REQUIRED_COLUMNS = ("timestamp", "open", "high", "low", "close", "volume")


class ReplayMarketDataProvider(MarketDataProvider):
    """Serve recorded bars for ``(instrument, timeframe)`` pairs."""

    name = "replay"

    def __init__(
        self,
        series: dict[tuple[str, str], tuple[MarketDataBar, ...]] | None = None,
        *,
        source: str = "replay:memory",
    ) -> None:
        super().__init__(source)
        self._series: dict[tuple[str, str], tuple[MarketDataBar, ...]] = dict(series or {})

    # -- construction --------------------------------------------------------
    def add(self, instrument: str, timeframe: str, bars: Iterable[MarketDataBar]) -> None:
        recorded = tuple(bars)
        if not recorded:
            raise MarketDataError(f"no recorded bars for {instrument} {timeframe}")
        for bar in recorded:
            if bar.instrument != instrument:
                raise MarketDataError(
                    f"bar instrument {bar.instrument!r} does not match {instrument!r}"
                )
        self._series[(instrument, timeframe)] = recorded

    @classmethod
    def from_bars(
        cls, bars: Iterable[MarketDataBar], timeframe: str, *, instrument: str = ""
    ) -> "ReplayMarketDataProvider":
        provider = cls(source="replay:bars")
        grouped: dict[str, list[MarketDataBar]] = {}
        for bar in bars:
            grouped.setdefault(instrument or bar.instrument, []).append(bar)
        for name, rows in grouped.items():
            provider.add(name, timeframe, rows)
        if not grouped:
            raise MarketDataError("from_bars requires at least one bar")
        return provider

    @classmethod
    def from_csv(
        cls,
        path: str | Path,
        timeframe: str,
        *,
        instrument: str | None = None,
        source: str | None = None,
    ) -> "ReplayMarketDataProvider":
        """Load a recorded CSV. The timeframe is DECLARED by the caller."""
        file_path = Path(path)
        if not file_path.exists():
            raise MarketDataError(f"replay file not found: {file_path}")
        provider = cls(source=source or f"replay:{file_path}")
        grouped: dict[str, list[MarketDataBar]] = {}
        with file_path.open(newline="", encoding="utf-8") as handle:
            reader = csv.DictReader(handle)
            missing = [c for c in REQUIRED_COLUMNS if c not in (reader.fieldnames or [])]
            if missing:
                raise MarketDataError(
                    f"{file_path.name} is missing required column(s): {', '.join(missing)}"
                )
            for index, row in enumerate(reader, start=2):
                if not row.get("timestamp"):
                    raise MarketDataError(f"{file_path.name} line {index}: empty timestamp")
                try:
                    bar = MarketDataBar.from_row(row, instrument=instrument or "")
                except MarketDataError as exc:
                    raise MarketDataError(f"{file_path.name} line {index}: {exc}") from exc
                grouped.setdefault(bar.instrument, []).append(bar)
        for name, rows in grouped.items():
            provider.add(name, timeframe, rows)
        if not grouped:
            raise MarketDataError(f"{file_path.name} contains no rows")
        return provider

    # -- MarketDataProvider --------------------------------------------------
    def instruments(self, timeframe: str | None = None) -> list[str]:
        return sorted(
            {name for name, tf in self._series if timeframe is None or tf == timeframe}
        )

    def timeframes(self, instrument: str | None = None) -> list[str]:
        return sorted(
            {tf for name, tf in self._series if instrument is None or name == instrument}
        )

    def fetch(
        self,
        instrument: str,
        timeframe: str,
        *,
        end: datetime | None = None,
        limit: int | None = None,
    ) -> MarketDataResult:
        self.check_timeframe(timeframe)
        key = (instrument, timeframe)
        if key not in self._series:
            available = ", ".join(
                f"{name}@{tf}" for name, tf in sorted(self._series)
            ) or "none"
            raise MarketDataError(
                f"no replayed series for {instrument}@{timeframe} (available: {available})"
            )
        bars = self._series[key]
        if end is not None:
            # Exclusive upper bound: walk-forward evaluation relies on this to
            # guarantee no future observation ever reaches the model.
            bars = tuple(bar for bar in bars if bar.timestamp < end)
        if limit is not None:
            if limit < 1:
                raise MarketDataError("limit must be >= 1")
            bars = bars[-limit:]
        return MarketDataResult(
            instrument=instrument,
            timeframe=timeframe,
            bars=bars,
            source=self.source,
            provider=self.name,
            retrieved_at=utcnow(),
            notes=("replayed recorded bars",) if bars else ("window is empty",),
        )
