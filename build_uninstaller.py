#!/usr/bin/env python3
"""Build the standalone Arena Deep Uninstaller executable.

    python build_uninstaller.py            # build for THIS platform
    python build_uninstaller.py --test     # build, then verify the artifact
    python build_uninstaller.py --onedir   # a folder instead of one file

On Windows this produces ``dist\\Arena-Uninstall.exe``: a single console
executable that removes an installed Arena and finds leftover/duplicate
Arena/AXIOM files. It bundles only ``uninstaller/`` — never the application —
so it works when Arena is closed, broken or gone.

The build is worthless if the artifact starts and then fails on a real scan,
so ``--test`` runs ``packaging/uninstaller_e2e.py`` against the ACTUAL binary:
scan a fake machine, review, cancel, confirm, quarantine, restore, and prove
that trading history, logs, configuration and credentials survive.

PyInstaller cannot cross-compile: a Windows .exe must be built on Windows.
CI does that in ``.github/workflows/arena-uninstaller-windows.yml`` and in
``.github/workflows/build-executable.yml``.
"""

from __future__ import annotations

import argparse
import importlib.util
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT / "packaging" / "uninstaller.spec"
DIST = ROOT / "dist"
BUILD = ROOT / "build" / "uninstaller"
ARTIFACT_NAME = "Arena-Uninstall.exe" if sys.platform == "win32" else "Arena-Uninstall"
ARTIFACT = DIST / ARTIFACT_NAME


def _tool_version() -> str:
    sys.path.insert(0, str(ROOT))
    try:
        from uninstaller import __version__
        return str(__version__)
    finally:
        sys.path.pop(0)


def ensure_pyinstaller() -> None:
    try:
        import PyInstaller  # noqa: F401
        return
    except ImportError:
        pass
    print("  PyInstaller is not installed; installing it now…", flush=True)
    code = subprocess.call([sys.executable, "-m", "pip", "install", "pyinstaller"])
    if code != 0:
        raise SystemExit(
            "Could not install PyInstaller. Install it with:\n"
            f"    {sys.executable} -m pip install pyinstaller")


def version_resource_text(version: str | None = None) -> str:
    """The Windows version resource, as PyInstaller's version-file syntax.

    ``ProductName`` must stay in sync with
    ``uninstaller.constants.TOOL_PRODUCT_NAME`` — the classifier uses it to
    recognise this tool (and stale copies of it) on a scanned drive.
    """
    version = version or _tool_version()
    parts = [int(p) if p.isdigit() else 0 for p in version.split(".")]
    while len(parts) < 4:
        parts.append(0)
    nums = tuple(parts[:4])
    return f"""# Generated by build_uninstaller.py — do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={nums},
    prodvers={nums},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '040904B0',
        [StringStruct('CompanyName', 'Thedivinetwilight'),
         StringStruct('FileDescription', 'AXIOM Arena Deep Uninstaller'),
         StringStruct('FileVersion', '{version}'),
         StringStruct('InternalName', 'Arena-Uninstall'),
         StringStruct('LegalCopyright', 'Copyright (c) Thedivinetwilight'),
         StringStruct('OriginalFilename', 'Arena-Uninstall.exe'),
         StringStruct('ProductName', 'AXIOM Arena Uninstall'),
         StringStruct('ProductVersion', '{version}')])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def write_version_resource() -> Path | None:
    """Write the version resource next to the build, on Windows only."""
    if sys.platform != "win32":
        return None
    text = version_resource_text()
    path = ROOT / "build" / "uninstaller-version.txt"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def build(onefile: bool) -> Path:
    ensure_pyinstaller()
    write_version_resource()
    BUILD.mkdir(parents=True, exist_ok=True)
    argv = [
        sys.executable, "-m", "PyInstaller", str(SPEC),
        "--noconfirm", "--clean",
        "--distpath", str(DIST), "--workpath", str(BUILD),
    ]
    if not onefile:
        argv.append("--onedir")
    print("  $ " + " ".join(argv), flush=True)
    code = subprocess.call(argv, cwd=str(ROOT))
    if code != 0:
        raise SystemExit(f"Build failed with exit code {code}.")
    if not ARTIFACT.exists():
        candidates = sorted(DIST.glob("Arena-Uninstall*"))
        if not candidates:
            raise SystemExit(f"Build reported success but {ARTIFACT} is missing.")
        return candidates[0]
    return ARTIFACT


def smoke_test(artifact: Path) -> bool:
    """Run the packaged-binary end-to-end suite against the real artifact."""
    spec = importlib.util.spec_from_file_location(
        "arena_uninstaller_e2e", ROOT / "packaging" / "uninstaller_e2e.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    result = module.run_uninstaller_e2e(artifact, ROOT / "build" / "uninstaller-e2e")
    for entry in result["results"]:
        mark = "ok  " if entry["ok"] else "FAIL"
        print(f"  [{mark}] {entry['name']}: {entry['detail']}")
    return bool(result["ok"])


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build Arena-Uninstall.")
    parser.add_argument("--test", action="store_true",
                        help="verify the built executable end-to-end")
    parser.add_argument("--onedir", action="store_true",
                        help="build a folder instead of a single file")
    args = parser.parse_args(argv)

    print(f"  platform : {sys.platform}  python {sys.version.split()[0]}")
    print(f"  output   : {ARTIFACT.name}")
    artifact = build(onefile=not args.onedir)
    size_mb = artifact.stat().st_size / (1024 * 1024)
    print(f"\n  built    : {artifact}  ({size_mb:.1f} MB)")
    if not args.test:
        return 0
    ok = smoke_test(artifact)
    print()
    if ok:
        print("  UNINSTALLER E2E PASSED — the artifact scans, reviews, cancels,")
        print("  confirms, quarantines, restores and preserves user data.")
    else:
        print("  UNINSTALLER E2E FAILED — do not ship this build.")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
